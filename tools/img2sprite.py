#!/usr/bin/env python3
"""Convert an animation (GIF, or a set of PNG frames, or a horizontal sprite
strip) into a C++ header holding a 1-bit gm::SpriteSheet for SpriteEffect.

Examples:
  tools/img2sprite.py anim.gif -o src/sprite_anim.hpp --name kAnim --width 24
  tools/img2sprite.py frames/*.png -o sprite.hpp --name kLogo --threshold 128 --invert
  tools/img2sprite.py strip.png --frames 12 -o sprite.hpp --name kStrip

Output layout (matches gm::SpriteSheet): frame-major, row-major, 1 bit per
pixel, MSB = leftmost pixel, each row padded to a whole byte.
"""
import argparse
import sys
from pathlib import Path

try:
    from PIL import Image, ImageSequence
except ImportError:  # pragma: no cover
    sys.exit("Pillow is required: pip install pillow")


def load_frames(paths, strip_frames):
    frames = []
    for p in paths:
        im = Image.open(p)
        if getattr(im, "is_animated", False):
            for fr in ImageSequence.Iterator(im):
                frames.append(fr.convert("LA"))
        elif strip_frames and strip_frames > 1:
            w = im.width // strip_frames
            for i in range(strip_frames):
                frames.append(im.crop((i * w, 0, (i + 1) * w, im.height)).convert("LA"))
        else:
            frames.append(im.convert("LA"))
    return frames


def to_bits(im, width, height, threshold, invert, dither):
    if (im.width, im.height) != (width, height):
        im = im.resize((width, height), Image.LANCZOS)
    # Composite transparent pixels onto black so they come out dark.
    l, a = im.split()
    gray = Image.composite(l, Image.new("L", im.size, 0), a)
    if invert:
        gray = gray.point(lambda v: 255 - v)
    if dither:
        bw = gray.convert("1")  # Floyd-Steinberg
    else:
        bw = gray.point(lambda v: 255 if v >= threshold else 0, mode="1")
    row_bytes = (width + 7) // 8
    out = bytearray(row_bytes * height)
    px = bw.load()
    for y in range(height):
        for x in range(width):
            if px[x, y]:
                out[y * row_bytes + (x >> 3)] |= 0x80 >> (x & 7)
    return bytes(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("inputs", nargs="+", help="GIF, PNG frames, or a sprite strip")
    ap.add_argument("-o", "--output", required=True, help="header to write")
    ap.add_argument("--name", default="kSprite", help="C++ identifier")
    ap.add_argument("--width", type=int, help="target width (default: source)")
    ap.add_argument("--height", type=int, help="target height (default: keep aspect)")
    ap.add_argument("--frames", type=int, default=0, help="split a horizontal strip into N frames")
    ap.add_argument("--threshold", type=int, default=128)
    ap.add_argument("--invert", action="store_true", help="dark pixels become lit")
    ap.add_argument("--dither", action="store_true", help="Floyd-Steinberg instead of threshold")
    args = ap.parse_args()

    frames = load_frames(args.inputs, args.frames)
    if not frames:
        sys.exit("no frames")
    src_w, src_h = frames[0].size
    width = args.width or src_w
    height = args.height or max(1, round(src_h * width / src_w))
    if width > 128 or height > 64:
        print(f"warning: {width}x{height} is larger than a panel", file=sys.stderr)

    data = b"".join(to_bits(f, width, height, args.threshold, args.invert, args.dither) for f in frames)
    lines = []
    lines.append("// Generated by tools/img2sprite.py -- do not edit.")
    lines.append(f"// {len(frames)} frames of {width}x{height}, 1 bpp, MSB first, byte-padded rows.")
    lines.append("#pragma once")
    lines.append("#include <cstdint>")
    lines.append('#include "gmeter/effects/sprite.hpp"')
    lines.append("")
    lines.append(f"static const uint8_t {args.name}Bits[{len(data)}] = {{")
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02X}" for b in data[i:i + 16])
        lines.append(f"  {chunk},")
    lines.append("};")
    lines.append(f"static const gm::SpriteSheet {args.name}{{{width}, {height}, {len(frames)}, {args.name}Bits}};")
    Path(args.output).write_text("\n".join(lines) + "\n")
    print(f"wrote {args.output}: {len(frames)} frames {width}x{height} ({len(data)} bytes)")


if __name__ == "__main__":
    main()
