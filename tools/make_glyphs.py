#!/usr/bin/env python3
"""Rasterize Japanese glyphs into 1-bit bitmaps for the voxel display.

Generates lib/gmeter_core/src/gmeter/jp_glyphs.cpp from the OFL-licensed Noto
Serif JP / Noto Sans JP fonts as published by Fontsource on npm, so the
firmware carries only the characters it uses (a few KB) and needs no font
files at build time.

  npm pack @fontsource/noto-serif-jp@5.3.1 @fontsource/noto-sans-jp@5.3.1
  pip install fonttools brotli pillow
  tools/make_glyphs.py --serif fontsource-noto-serif-jp-5.3.1.tgz \\
                       --sans fontsource-noto-sans-jp-5.3.1.tgz --preview glyphs.png

To add characters, edit LARGE_TEXT / SMALL_TEXT below and run it again.
"""
import argparse
import io
import re
import sys
import tarfile
from pathlib import Path

try:
    from PIL import Image, ImageDraw, ImageFont
    from fontTools.ttLib import TTFont
except ImportError:  # pragma: no cover
    sys.exit("needs: pip install fonttools brotli pillow")

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "lib" / "gmeter_core" / "src" / "gmeter" / "jp_glyphs.cpp"

# Every character the effects draw. Large: state words (title-card style).
LARGE_TEXT = "待機加速制動左右旋回衝撃警告危険"
# Small: labels, status columns and captions.
SMALL_TEXT = "横縦上下同期率正常異常重力警告危険限界活動使徒接近反応全開待機中加速制動旋回衝撃左右" \
             "パターン青フィールド第号機"

FONTS = {
    # name: (package option, weight, pixel size, horizontal condense, threshold 0..255)
    "large": ("serif", 900, 24, 0.78, 120),
    "small": ("sans", 700, 14, 0.86, 110),
}


def subset_files(tgz, weight, family_prefix, chars):
    """Map each character to the woff2 subset file that contains it."""
    with tarfile.open(tgz) as tar:
        css = tar.extractfile(f"package/{weight}.css").read().decode()
        blocks = re.findall(r"src: url\(\./files/([^)]+?\.woff2)\).*?unicode-range: ([^;]+);", css, re.S)
        ranges = []
        for fname, rng in blocks:
            for part in rng.split(","):
                part = part.strip().lower().replace("u+", "")
                if "-" in part:
                    a, b = part.split("-")
                    ranges.append((int(a, 16), int(b, 16), fname))
                else:
                    ranges.append((int(part, 16), int(part, 16), fname))
        need = {}
        for ch in chars:
            cp = ord(ch)
            hit = next((f for a, b, f in ranges if a <= cp <= b), None)
            if not hit:
                sys.exit(f"no subset contains {ch} (U+{cp:04X})")
            need.setdefault(hit, []).append(ch)
        fonts = {}
        for fname in need:
            data = tar.extractfile(f"package/files/{fname}").read()
            tt = TTFont(io.BytesIO(data))
            tt.flavor = None
            buf = io.BytesIO()
            tt.save(buf)
            fonts[fname] = buf.getvalue()
        return {ch: fonts[f] for f, chs in need.items() for ch in chs}


def rasterize(ch, ttf_bytes, size, condense, threshold):
    font = ImageFont.truetype(io.BytesIO(ttf_bytes), size * 4)  # 4x supersample
    big = size * 4
    img = Image.new("L", (big * 2, big * 2), 0)
    d = ImageDraw.Draw(img)
    # Centre the glyph's ink box in an em square.
    l, t, r, b = d.textbbox((0, 0), ch, font=font)
    ascent, descent = font.getmetrics()
    x = (big * 2 - big) // 2
    y = (big * 2 - big) // 2 - (ascent - big) // 1 - big // 12
    d.text((x, y), ch, fill=255, font=font)
    em = img.crop((x, (big * 2 - big) // 2, x + big, (big * 2 - big) // 2 + big))
    w = max(1, round(size * condense))
    small = em.resize((w, size), Image.LANCZOS)
    bits = [[1 if small.getpixel((xx, yy)) >= threshold else 0 for xx in range(w)] for yy in range(size)]
    return w, bits


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--serif", required=True, help="fontsource-noto-serif-jp-*.tgz")
    ap.add_argument("--sans", required=True, help="fontsource-noto-sans-jp-*.tgz")
    ap.add_argument("--preview", help="write a PNG preview of every glyph")
    ap.add_argument("-o", "--output", default=str(OUT))
    args = ap.parse_args()

    texts = {"large": LARGE_TEXT, "small": SMALL_TEXT}
    out = {}
    for name, (fam, weight, size, condense, thr) in FONTS.items():
        chars = sorted(set(texts[name]), key=ord)
        tgz = args.serif if fam == "serif" else args.sans
        files = subset_files(tgz, weight, fam, chars)
        out[name] = (size, [(ch,) + rasterize(ch, files[ch], size, condense, thr) for ch in chars])

    lines = [
        "// Generated by tools/make_glyphs.py -- do not edit by hand.",
        "//",
        "// Glyph bitmaps rasterized from Noto Serif JP Black (large) and Noto Sans",
        "// JP Bold (small) as packaged by Fontsource, Copyright Google Inc., licensed under",
        "// the SIL Open Font License, Version 1.1 (see docs/THIRD_PARTY.md). This",
        "// file is a modified, subset version of those fonts and remains under the",
        "// OFL; the rest of the project is MIT licensed.",
        '#include "jp_text.hpp"',
        "",
        "namespace gm {",
        "namespace {",
    ]
    for name, (size, glyphs) in out.items():
        for ch, w, bits in glyphs:
            rb = (w + 7) // 8
            data = []
            for row in bits:
                for byte in range(rb):
                    v = 0
                    for bit in range(8):
                        x = byte * 8 + bit
                        if x < w and row[x]:
                            v |= 0x80 >> bit
                    data.append(v)
            lines.append(f"const uint8_t k_{name}_{ord(ch):04X}[] = {{{', '.join(f'0x{b:02X}' for b in data)}}};  // {ch}")
        lines.append(f"const JpGlyph k_{name}_glyphs[] = {{")
        for ch, w, bits in glyphs:
            lines.append(f"    {{0x{ord(ch):04X}, {w}, k_{name}_{ord(ch):04X}}},")
        lines.append("};")
    lines.append("}  // namespace")
    lines.append("")
    for name, (size, glyphs) in out.items():
        lines.append(f"const JpFont kJp{name.capitalize()} = {{{size}, {len(glyphs)}, k_{name}_glyphs}};")
    lines.append("")
    lines.append("}  // namespace gm")
    Path(args.output).write_text("\n".join(lines) + "\n", encoding="utf-8")
    total = sum(((w + 7) // 8) * size for size, gl in out.values() for _, w, _ in gl)
    print(f"wrote {args.output}: {sum(len(g) for _, g in out.values())} glyphs, {total} bytes of bitmaps")

    if args.preview:
        scale = 4
        rows = []
        for name, (size, glyphs) in out.items():
            width = sum(w + 2 for _, w, _ in glyphs)
            img = Image.new("L", (width, size + 2), 0)
            x = 1
            for ch, w, bits in glyphs:
                for yy, row in enumerate(bits):
                    for xx, v in enumerate(row):
                        if v:
                            img.putpixel((x + xx, 1 + yy), 255)
                x += w + 2
            rows.append(img)
        W = max(r.width for r in rows)
        H = sum(r.height + 4 for r in rows)
        sheet = Image.new("L", (W, H), 30)
        y = 0
        for r in rows:
            sheet.paste(r, (0, y))
            y += r.height + 4
        sheet = sheet.resize((W * scale, H * scale), Image.NEAREST)
        sheet.save(args.preview)
        print(f"preview {args.preview}")


if __name__ == "__main__":
    main()
